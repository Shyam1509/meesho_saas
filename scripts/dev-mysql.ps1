<#
.SYNOPSIS
  Local development MySQL 8 instance for meesho_saas on Windows. Runs as the current user, not as a service.

.DESCRIPTION
  Uses the binaries of an installed MySQL Server 8.x with its own data directory, so an installed MySQL
  Windows service is never touched. Defaults: home D:\meesho_saas_mysql, port 3307, 127.0.0.1 only.

  init    Write my.ini, initialise the data directory, start the server, set a random root password,
          create meesho_dev and meesho_test (utf8mb4) and one least-privilege user per database
          (meesho_app -> meesho_dev, meesho_test_app -> meesho_test). Credentials are written to
          <home>\root.cnf, app.cnf/app.secret and test.cnf/test.secret - never into the repository.
  start   Start the server in the background.
  stop    Clean shutdown via mysqladmin.
  status  Report whether the port is listening and the server version.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File scripts\dev-mysql.ps1 status
#>
param(
  [Parameter(Position = 0, Mandatory = $true)]
  [ValidateSet('init', 'start', 'stop', 'status')]
  [string]$Action,
  [string]$MySqlHome = $(if ($env:MEESHO_MYSQL_HOME) { $env:MEESHO_MYSQL_HOME } else { 'D:\meesho_saas_mysql' }),
  [string]$MySqlBin = $(if ($env:MEESHO_MYSQL_BIN) { $env:MEESHO_MYSQL_BIN } else { 'C:\Program Files\MySQL\MySQL Server 8.0\bin' }),
  [int]$Port = 3307
)
$ErrorActionPreference = 'Stop'

$ini = Join-Path $MySqlHome 'my.ini'
$dataDir = Join-Path $MySqlHome 'data'
$errLog = Join-Path $MySqlHome 'mysqld.err'
$rootCnf = Join-Path $MySqlHome 'root.cnf'
$appCnf = Join-Path $MySqlHome 'app.cnf'
$appSecret = Join-Path $MySqlHome 'app.secret'
$testCnf = Join-Path $MySqlHome 'test.cnf'
$testSecret = Join-Path $MySqlHome 'test.secret'
$mysqld = Join-Path $MySqlBin 'mysqld.exe'
$mysql = Join-Path $MySqlBin 'mysql.exe'
$mysqladmin = Join-Path $MySqlBin 'mysqladmin.exe'

function Test-Listening {
  [bool](Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue)
}

# UTF-8 without BOM: MySQL option files must not start with a BOM.
function Write-PlainFile([string]$Path, [string]$Content) {
  [IO.File]::WriteAllText($Path, $Content, (New-Object Text.UTF8Encoding $false))
}

# Only the current user and SYSTEM may read the data directory and credential files.
function Protect-Folder([string]$Path) {
  $me = [Security.Principal.WindowsIdentity]::GetCurrent().Name
  & icacls $Path /inheritance:r /grant:r "${me}:(OI)(CI)F" 'SYSTEM:(OI)(CI)F' | Out-Null
  if ($LASTEXITCODE -ne 0) { throw "icacls failed on $Path" }
}

# Best-effort shutdown after a failed init, so a server with a passwordless root is not left running.
function Stop-AfterFailedInit {
  if (Test-Path $rootCnf) { & $mysqladmin "--defaults-extra-file=$rootCnf" shutdown 2>$null }
  if (Test-Listening) { & $mysqladmin --no-defaults --protocol=TCP '--host=127.0.0.1' "--port=$Port" '--user=root' shutdown 2>$null }
}

function New-Password {
  $bytes = New-Object byte[] 18
  [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
  [Convert]::ToBase64String($bytes).TrimEnd('=').Replace('+', '-').Replace('/', '_')
}

function Start-Instance {
  if (Test-Listening) { Write-Output "Port $Port is already listening."; return }
  if (-not (Test-Path $ini)) { throw "No $ini - run 'init' first." }
  Start-Process -FilePath $mysqld -ArgumentList "--defaults-file=`"$ini`"" -WindowStyle Hidden | Out-Null
  for ($i = 0; $i -lt 60; $i++) {
    if (Test-Listening) { Write-Output "MySQL listening on 127.0.0.1:$Port"; return }
    Start-Sleep -Milliseconds 500
  }
  throw "MySQL did not start; see $errLog"
}

function Initialize-Instance {
  if ((Test-Path $dataDir) -and (Get-ChildItem $dataDir -Force | Select-Object -First 1)) {
    throw "$dataDir is not empty - already initialised."
  }
  if (Test-Listening) { throw "Port $Port is already in use." }
  New-Item -ItemType Directory -Force -Path (Join-Path $MySqlHome 'tmp') | Out-Null
  Protect-Folder $MySqlHome
  $h = $MySqlHome.Replace('\', '/')
  $b = (Split-Path $MySqlBin -Parent).Replace('\', '/')
  Write-PlainFile $ini @"
# Local dev MySQL for meesho_saas (user-run, not a Windows service). Generated by scripts/dev-mysql.ps1.
[mysqld]
basedir="$b"
datadir="$h/data"
tmpdir="$h/tmp"
log-error="$h/mysqld.err"
pid-file="$h/mysqld.pid"
port=$Port
bind-address=127.0.0.1
mysqlx=OFF
character-set-server=utf8mb4
collation-server=utf8mb4_0900_ai_ci
default-time-zone='+00:00'
innodb_buffer_pool_size=128M
innodb_redo_log_capacity=64M
max_connections=50

[client]
port=$Port
host=127.0.0.1
default-character-set=utf8mb4
"@
  & $mysqld "--defaults-file=$ini" --initialize-insecure
  if ($LASTEXITCODE -ne 0) { throw "mysqld --initialize-insecure failed; see $errLog" }
  Start-Instance
  try {
    Set-Credentials
  } catch {
    Stop-AfterFailedInit
    throw
  }
  Write-Output "Initialised. Credentials written to $rootCnf, $appCnf, $appSecret, $testCnf and $testSecret (outside the repo)."
}

function Set-Credentials {
  $rootPw = New-Password
  $appPw = New-Password
  $testPw = New-Password
  $privs = 'SELECT, INSERT, UPDATE, DELETE, CREATE, DROP, ALTER, INDEX, REFERENCES, CREATE TEMPORARY TABLES, LOCK TABLES, CREATE VIEW, SHOW VIEW'
  # One user per database, so tests (meesho_test_app) physically cannot reach meesho_dev.
  $sql = @"
ALTER USER 'root'@'localhost' IDENTIFIED BY '$rootPw';
CREATE DATABASE IF NOT EXISTS meesho_dev  CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
CREATE DATABASE IF NOT EXISTS meesho_test CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
CREATE USER IF NOT EXISTS 'meesho_app'@'localhost' IDENTIFIED BY '$appPw';
CREATE USER IF NOT EXISTS 'meesho_test_app'@'localhost' IDENTIFIED BY '$testPw';
GRANT $privs ON meesho_dev.*  TO 'meesho_app'@'localhost';
GRANT $privs ON meesho_test.* TO 'meesho_test_app'@'localhost';
"@
  # Write the credential files first so a generated password is never lost.
  Write-PlainFile $rootCnf "[client]`nuser=root`npassword=$rootPw`nhost=127.0.0.1`nport=$Port`nprotocol=TCP`n"
  Write-PlainFile $appCnf "[client]`nuser=meesho_app`npassword=$appPw`nhost=127.0.0.1`nport=$Port`nprotocol=TCP`n"
  Write-PlainFile $appSecret "DB_HOST=127.0.0.1`nDB_PORT=$Port`nDB_USER=meesho_app`nDB_PASSWORD=$appPw`nDB_NAME=meesho_dev`n"
  Write-PlainFile $testCnf "[client]`nuser=meesho_test_app`npassword=$testPw`nhost=127.0.0.1`nport=$Port`nprotocol=TCP`n"
  Write-PlainFile $testSecret "DB_HOST=127.0.0.1`nDB_PORT=$Port`nDB_USER=meesho_test_app`nDB_PASSWORD=$testPw`nDB_NAME=meesho_test`n"

  # Long-form options: PowerShell would split a bare -h127.0.0.1 into two arguments.
  $sql | & $mysql --no-defaults --protocol=TCP '--host=127.0.0.1' "--port=$Port" '--user=root'
  if ($LASTEXITCODE -ne 0) { throw 'Securing root / creating databases failed.' }
}

switch ($Action) {
  'init' { Initialize-Instance }
  'start' { Start-Instance }
  'stop' {
    if (-not (Test-Listening)) { Write-Output "Nothing listening on port $Port."; return }
    if (-not (Test-Path $rootCnf)) { throw "$rootCnf is missing; cannot shut down cleanly." }
    & $mysqladmin "--defaults-extra-file=$rootCnf" shutdown
    if ($LASTEXITCODE -ne 0) { throw 'mysqladmin shutdown failed.' }
    for ($i = 0; $i -lt 60; $i++) {
      if (-not (Test-Listening)) { Write-Output 'MySQL stopped.'; return }
      Start-Sleep -Milliseconds 500
    }
    throw "MySQL still listening on port $Port."
  }
  'status' {
    if (-not (Test-Listening)) { Write-Output "Stopped (nothing listening on 127.0.0.1:$Port)."; return }
    if (-not (Test-Path $appCnf)) { Write-Output "Port $Port is listening, but $appCnf is missing."; return }
    $version = & $mysql "--defaults-extra-file=$appCnf" -N -e 'SELECT VERSION()'
    Write-Output "Running on 127.0.0.1:$Port, MySQL $version"
  }
}
